def plot_cold(cold: pd.DataFrame, main: pd.DataFrame):
    d = cold.copy()
    fig, axes = plt.subplots(1, 2, figsize=(8.6, 3.2))
    labels = [m.replace("Ours: ", "").replace(" (", "\n(") for m in d["method"]]
    y = np.arange(len(d))[::-1]
    for ax, col, title, pct in ((axes[0], "hr@10", "Cold-start HR@10", False), (axes[1], "violation@10", "Cold-start violation@10", True)):
        vals = d[col].to_numpy()
        ax.barh(y, vals, color=SERIES[0], height=0.6)
        for yi, v in zip(y, vals):
            ax.text(v, yi, f" {v:.1%}" if pct else f" {v:.3f}", va="center", fontsize=7, color="#0b0b0b")
        ax.set_yticks(y, labels if ax is axes[0] else [""] * len(y), fontsize=7)
        ax.set_title(title)
        ax.grid(axis="y", visible=False)
        ax.set_xlim(0, max(vals.max() * 1.3, 1e-3))
        if pct:
            ax.xaxis.set_major_formatter(lambda x, _: f"{x:.0%}")
    fig.tight_layout()
    save(fig, os.path.join(FIG, "offline_coldstart.png"))


