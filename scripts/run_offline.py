def plot_tradeoff(trade: pd.DataFrame):
    fig, ax = plt.subplots(figsize=(6.4, 4.0))
    curves = [("BPR-MF + penalty β", SERIES[0], "o"), ("A + penalty β (ours)", SERIES[1], "s"),
              ("A + B (λ sweep, no rerank)", SERIES[2], "^"), ("A + pop. calibration + penalty β (ours v2)", SERIES[3], "D")]
    for name, color, marker in curves:
        d = trade[trade["curve"] == name].sort_values("violation@10")
        if d.empty:
            continue
        ax.plot(100 * d["violation@10"], d["ndcg@10"], color=color, lw=2, marker=marker, ms=6, label=name)
    for name, marker in (("MostPop", "D"), ("HealthyPop", "P")):
        d = trade[trade["curve"] == name].iloc[0]
        ax.scatter(100 * d["violation@10"], d["ndcg@10"], color="#52514e", marker=marker, s=50, zorder=5)
        ax.annotate(name, (100 * d["violation@10"], d["ndcg@10"]), textcoords="offset points", xytext=(6, 4),
                    fontsize=8, color=TEXT_SECONDARY)
    ax.set_xlabel("Health violation@10 (% of top-10 recipes violating the user's conditions)")
    ax.set_ylabel("NDCG@10 (test)")
    ax.set_title("Accuracy vs. health violation (up-left is better)")
    ax.legend(loc="lower right")
    save(fig, os.path.join(FIG, "offline_tradeoff.png"))


