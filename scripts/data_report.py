"""
Dataset statistics tables and EDA figures for the report (run after scripts/prepare_data.py).

    python scripts/data_report.py

Outputs: outputs/tables/*.csv + dataset_stats.md, outputs/figures/data_*.png
"""
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.config import get_project_root, load_config, get_outputs_dir  # noqa: E402
from src.utils.plotting import GRID, SERIES, TEXT_SECONDARY, plt, save, set_style  # noqa: E402

COND_LABEL = {"diabetes": "Diabetes", "hypertension": "Hypertension", "hyperuricemia": "Hyperuricemia"}


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def fmt_int(x) -> str:
    return f"{int(x):,}"


def main():
    root = get_project_root()
    cfg, rules = load_config("data"), load_config("health_rules")
    proc = os.path.join(root, cfg["paths"]["processed_dir"])
    fig_dir = get_outputs_dir("figures")
    tab_dir = get_outputs_dir("tables")
    os.makedirs(fig_dir, exist_ok=True)
    os.makedirs(tab_dir, exist_ok=True)
    set_style()

    summary = json.load(open(os.path.join(proc, "summary.json")))
    catalog = pd.read_parquet(os.path.join(proc, "recipes.parquet"))
    all_rec = pd.read_parquet(os.path.join(proc, "recipes_all.parquet"))
    inter = pd.read_parquet(os.path.join(proc, "interactions.parquet"))
    cold = pd.read_parquet(os.path.join(proc, "cold_start.parquet"))
    profiles = pd.read_csv(os.path.join(proc, "profiles.csv"), dtype={"user_idx": "Int64"})
    conditions = list(rules["conditions"])
    allergens = list(rules["allergens"])
    md = ["# Dataset statistics\n", "Generated by `scripts/data_report.py`. Food.com (Kaggle irkaal), nutrition per serving.\n"]

    # ---- Table 1: processing funnel
    def row(stage, s):
        return {"Stage": stage, "Users": fmt_int(s["users"]), "Recipes": fmt_int(s["items"]),
                "Interactions": fmt_int(s["interactions"]), "Density": f"{s['density']:.2e}"}
    funnel = pd.DataFrame([
        row("Raw reviews (all ratings)", summary["raw_reviews"]),
        row("Positives (rating >= 4, clean recipes)", summary["positives"]),
        row(f"{cfg['kcore']}-core (warm users)", summary["kcore"]),
        row("Cold-start users (sampled)", summary["cold_start"]),
    ])
    funnel.to_csv(os.path.join(tab_dir, "dataset_funnel.csv"), index=False)
    rm = summary["cleaning_removed"]
    md += ["## 1. Processing funnel\n", md_table(funnel), "",
           f"Recipes: {fmt_int(summary['raw_recipes'])} raw -> {fmt_int(summary['clean_recipes'])} after cleaning "
           f"(removed: {rm['zero_calories']:,} with 0 kcal, {rm['calories_gt_max']:,} > {cfg['cleaning']['max_calories']} kcal/serving, "
           f"{rm['sodium_outlier']:,} sodium > {rm['sodium_cap_mg']:,.0f} mg (99.9th pct), {rm['no_ingredients']:,} without ingredients) "
           f"-> {fmt_int(summary['catalog_items'])} in the k-core catalog.",
           f"Ratings of 0 ({summary['rating_counts']['0']:,}, reviews without stars) are dropped; ratings 1–3 on catalog recipes "
           f"({fmt_int(summary['nonpos_pairs'])} pairs) are excluded from negative sampling.\n"]

    # ---- Table 2: splits
    per_user = inter.groupby("UserId").size()
    per_item = inter.groupby("RecipeId").size()
    split = pd.DataFrame([
        {"Split": "Train", "Interactions": fmt_int(summary["split_sizes"]["train"]), "Users": fmt_int(summary["kcore"]["users"])},
        {"Split": "Validation (2nd-last positive)", "Interactions": fmt_int(summary["split_sizes"]["val"]), "Users": fmt_int(summary["kcore"]["users"])},
        {"Split": "Test (last positive)", "Interactions": fmt_int(summary["split_sizes"]["test"]), "Users": fmt_int(summary["kcore"]["users"])},
        {"Split": "Cold-start test", "Interactions": fmt_int(len(cold)), "Users": fmt_int(cold["UserId"].nunique())},
    ])
    split.to_csv(os.path.join(tab_dir, "dataset_splits.csv"), index=False)
    md += ["## 2. Splits (temporal leave-one-out)\n", md_table(split), "",
           f"Warm users: {per_user.mean():.1f} positives on average (median {per_user.median():.0f}, max {per_user.max():,}); "
           f"recipes: {per_item.mean():.1f} positives on average (median {per_item.median():.0f}). "
           f"Positive period: {inter['DateSubmitted'].min():%Y-%m} to {inter['DateSubmitted'].max():%Y-%m}. "
           f"Cold-start users have {cold.groupby('UserId').size().mean():.2f} target recipes on average and no training history.\n"]

    # ---- Table 3: nutrition per serving (catalog)
    nut = {"Calories": "Energy (kcal)", "CarbohydrateContent": "Carbohydrate (g)", "SugarContent": "Sugars (g)",
           "SodiumContent": "Sodium (mg)", "SaturatedFatContent": "Saturated fat (g)", "FatContent": "Fat (g)",
           "ProteinContent": "Protein (g)", "FiberContent": "Fiber (g)", "CholesterolContent": "Cholesterol (mg)"}
    q = catalog[list(nut)].quantile([0.25, 0.5, 0.75, 0.95]).T
    nut_tab = pd.DataFrame({"Nutrient (per serving)": [nut[c] for c in nut],
                            "Mean": catalog[list(nut)].mean().round(1).values,
                            "P25": q[0.25].round(1).values, "Median": q[0.5].round(1).values,
                            "P75": q[0.75].round(1).values, "P95": q[0.95].round(1).values})
    nut_tab.to_csv(os.path.join(tab_dir, "nutrition_per_serving.csv"), index=False)
    md += ["## 3. Nutrition per serving (catalog recipes)\n", md_table(nut_tab), ""]

    # ---- Table 4: health labels
    rule_txt = {}
    for c, spec in rules["conditions"].items():
        parts = [f"{k.replace('Content', '')} <= {v}" for k, v in spec.get("nutrient_max", {}).items()]
        parts += [f"no {g.replace('_', '-')}" for g in spec.get("ingredients_forbidden", [])]
        rule_txt[c] = "; ".join(parts)
    pos_ok = inter.join(catalog.set_index("item_idx")[[f"ok_{c}" for c in conditions]], on="item_idx")
    health = pd.DataFrame([{
        "Condition": COND_LABEL[c],
        "Rule (per serving)": rule_txt[c],
        "Compliant: all clean recipes": f"{all_rec[f'ok_{c}'].mean():.1%}",
        "Compliant: catalog": f"{catalog[f'ok_{c}'].mean():.1%}",
        "Compliant: positive interactions": f"{pos_ok[f'ok_{c}'].mean():.1%}",
    } for c in conditions])
    health.to_csv(os.path.join(tab_dir, "health_labels.csv"), index=False)
    md += ["## 4. Guideline-based health labels\n", md_table(health), "",
           "Sodium/saturated fat/sugar: UK FoP 'high' per-portion thresholds and ACC/AHA 2017 (1500 mg/day ÷ 3); "
           "carbohydrate: ADA 45–60 g per meal; hyperuricemia ingredient rules: ACR 2020 gout guideline. "
           "Sources in `configs/health_rules.yaml`.\n"]

    # ---- Table 5: external validity check against Food.com's own keyword tags
    kw = catalog["Keywords"].map(set)
    checks = [("Very Low Carbs", "diabetes"), ("Healthy", "diabetes"), ("Healthy", "hypertension"),
              ("Low Cholesterol", "hypertension"), ("Dessert", "diabetes")]
    valid = []
    for tag, c in checks:
        has = kw.map(lambda s, t=tag: t in s)
        valid.append({"Food.com tag": tag, "Condition": COND_LABEL[c], "Tagged recipes": fmt_int(has.sum()),
                      "Compliant (tagged)": f"{catalog.loc[has, f'ok_{c}'].mean():.1%}",
                      "Compliant (untagged)": f"{catalog.loc[~has, f'ok_{c}'].mean():.1%}"})
    valid = pd.DataFrame(valid)
    valid.to_csv(os.path.join(tab_dir, "health_label_validation.csv"), index=False)
    md += ["## 5. Sanity check: our labels vs Food.com keyword tags\n", md_table(valid), "",
           "Tags are assigned by Food.com independently of our thresholds. 'Very Low Carbs', 'Low Cholesterol' and 'Dessert' "
           "agree with our labels in the expected direction. 'Healthy' is *less* diabetes-compliant than untagged recipes: "
           "Food.com's 'Healthy' mostly means low-fat (often fruit-, grain- or sugar-heavy), which is exactly why generic "
           "'healthy' tags are not enough for condition-specific recommendation. No tag exists for sodium or purines.\n"]

    # ---- Table 6: synthetic profiles
    cond_lists = profiles["conditions"].map(json.loads)
    alg_lists = profiles["allergies"].map(json.loads)
    prof_rows = [{"Attribute": COND_LABEL[c], "Target prevalence": f"{p:.1%}",
                  "Realised": f"{cond_lists.map(lambda l, c=c: c in l).mean():.1%}"}
                 for c, p in rules["prevalence"]["conditions"].items()]
    prof_rows.append({"Attribute": ">= 1 condition", "Target prevalence": "-",
                      "Realised": f"{(cond_lists.map(len) > 0).mean():.1%}"})
    prof_rows += [{"Attribute": f"Allergy: {a.replace('_', ' ')}", "Target prevalence": f"{p:.1%}",
                   "Realised": f"{alg_lists.map(lambda l, a=a: a in l).mean():.2%}"}
                  for a, p in rules["prevalence"]["allergies"].items()]
    prof = pd.DataFrame(prof_rows)
    prof.to_csv(os.path.join(tab_dir, "profiles_prevalence.csv"), index=False)
    md += ["## 6. Synthetic health profiles\n",
           f"{len(profiles):,} profiles ({(profiles['source'] == 'foodcom_warm').sum():,} warm + "
           f"{(profiles['source'] == 'foodcom_cold').sum():,} cold-start), seed {cfg['seed']}. Conditions are drawn "
           "independently of rating history; an allergy is only assigned if none of the user's positive recipes contains "
           "that allergen, so realised allergy rates are below population rates for ubiquitous allergens (milk, egg, wheat).\n",
           md_table(prof), ""]

    with open(os.path.join(tab_dir, "dataset_stats.md"), "w") as f:
        f.write("\n".join(md) + "\n")

    # ================= figures =================
    # Fig 1: rating distribution
    rc = pd.Series(summary["rating_counts"]).astype(int)
    rc.index = rc.index.astype(int)
    fig, ax = plt.subplots(figsize=(5.2, 3.0))
    colors = [GRID if r == 0 else (SERIES[0] if r >= cfg["ratings"]["positive_threshold"] else "#a9a8a3") for r in rc.index]
    ax.bar(rc.index, rc.values, color=colors, width=0.7)
    for r, v in rc.items():
        ax.text(r, v, f"{v / rc.sum():.1%}", ha="center", va="bottom", fontsize=7, color=TEXT_SECONDARY)
    ax.set_xticks(rc.index, ["0\n(no star)", "1", "2", "3", "4", "5"])
    ax.set_xlabel("Rating")
    ax.set_ylabel("Reviews")
    ax.yaxis.set_major_formatter(lambda x, _: f"{x / 1e6:.1f}M" if x >= 1e6 else f"{x / 1e3:.0f}k")
    ax.set_title("Rating distribution (all 1.4M reviews)")
    ax.text(0.02, 0.92, "blue = positive (>= 4); 0 = dropped", transform=ax.transAxes, fontsize=7, color=TEXT_SECONDARY)
    ax.grid(axis="x", visible=False)
    save(fig, os.path.join(fig_dir, "data_rating_distribution.png"))

    # Fig 2: long tail (rank-frequency, log-log), small multiples
    fig, axes = plt.subplots(1, 2, figsize=(8.4, 3.0))
    for ax, counts, name in [(axes[0], per_user, "Users"), (axes[1], per_item, "Recipes")]:
        s = np.sort(counts.to_numpy())[::-1]
        ax.loglog(np.arange(1, len(s) + 1), s, color=SERIES[0], lw=2)
        ax.set_xlabel(f"{name} ranked by # positives")
        ax.set_ylabel("# positives (train+val+test)")
        top = s[: max(1, len(s) // 10)].sum() / s.sum()
        ax.set_title(f"{name}: top 10% hold {top:.0%}", fontsize=9.5)
    fig.suptitle(f"Long-tail activity in the {cfg['kcore']}-core data (rank vs. # positives, log-log)", x=0.01, ha="left", fontsize=11, fontweight="bold")
    fig.tight_layout()
    save(fig, os.path.join(fig_dir, "data_long_tail.png"))

    # Fig 3: nutrition distributions with guideline thresholds (small multiples)
    panels = [("CarbohydrateContent", "Carbohydrate (g)", [("Diabetes", rules["conditions"]["diabetes"]["nutrient_max"]["CarbohydrateContent"])]),
              ("SugarContent", "Sugars (g)", [("Diabetes / hyperuricemia", rules["conditions"]["diabetes"]["nutrient_max"]["SugarContent"])]),
              ("SodiumContent", "Sodium (mg)", [("Hypertension", rules["conditions"]["hypertension"]["nutrient_max"]["SodiumContent"])]),
              ("SaturatedFatContent", "Saturated fat (g)", [("Hypertension", rules["conditions"]["hypertension"]["nutrient_max"]["SaturatedFatContent"])]),
              ("Calories", "Energy (kcal)", []),
              ("ProteinContent", "Protein (g)", [])]
    fig, axes = plt.subplots(2, 3, figsize=(8.4, 4.6))
    for ax, (col, label, thr) in zip(axes.flat, panels):
        x = catalog[col]
        hi = x.quantile(0.99)
        ax.hist(x[x <= hi], bins=50, range=(0, hi), color=SERIES[0], edgecolor="white", linewidth=0.3)
        for name, t in thr:
            ax.axvline(t, color="#0b0b0b", lw=1.2, ls="--")
            share = (x > t).mean()
            ax.text(t, ax.get_ylim()[1] * 0.95, f" {name}\n limit {t}: {share:.0%} above", fontsize=6.5,
                    va="top", ha="left", color="#0b0b0b")
        ax.set_xlabel(label + " per serving")
        ax.set_yticks([])
        ax.grid(False)
        ax.spines["left"].set_visible(False)
    fig.suptitle("Nutrition per serving in the catalog with guideline limits (values above P99 not shown)",
                 x=0.01, ha="left", fontsize=11, fontweight="bold")
    fig.tight_layout()
    save(fig, os.path.join(fig_dir, "data_nutrition.png"))

    # Fig 4: compliance per condition + allergen presence (two panels, shared form: horizontal bars)
    fig, axes = plt.subplots(1, 2, figsize=(8.0, 2.9), gridspec_kw={"width_ratios": [1, 1.3]})
    comp = pd.Series({COND_LABEL[c]: catalog[f"ok_{c}"].mean() for c in conditions}).sort_values()
    axes[0].barh(comp.index, comp.values, color=SERIES[0], height=0.55)
    for i, v in enumerate(comp.values):
        axes[0].text(v + 0.01, i, f"{v:.0%}", va="center", fontsize=8, color="#0b0b0b")
    axes[0].set_xlim(0, 1.1)
    axes[0].set_xticks([0, 0.5, 1], ["0%", "50%", "100%"])
    axes[0].set_title("Recipes compliant per condition")
    axes[0].grid(axis="y", visible=False)
    alg = pd.Series({a.replace("_", " "): catalog[f"contains_{a}"].mean() for a in allergens}).sort_values()
    axes[1].barh(alg.index, alg.values, color=SERIES[0], height=0.6)
    for i, v in enumerate(alg.values):
        axes[1].text(v + 0.01, i, f"{v:.1%}", va="center", fontsize=7.5, color="#0b0b0b")
    axes[1].set_xlim(0, alg.max() * 1.25)
    axes[1].xaxis.set_major_formatter(lambda x, _: f"{x:.0%}")
    axes[1].set_title("Recipes containing each allergen")
    axes[1].grid(axis="y", visible=False)
    fig.tight_layout()
    save(fig, os.path.join(fig_dir, "data_health_labels.png"))

    # Fig 5: positives per year (motivates the temporal split)
    yearly = inter.groupby(inter["DateSubmitted"].dt.year).size()
    fig, ax = plt.subplots(figsize=(5.2, 2.6))
    ax.plot(yearly.index, yearly.values, color=SERIES[0], lw=2, marker="o", ms=3.5)
    ax.set_xlabel("Year")
    ax.xaxis.set_major_locator(plt.MaxNLocator(integer=True))
    ax.set_ylabel("Positive interactions")
    ax.yaxis.set_major_formatter(lambda x, _: f"{x / 1e3:.0f}k")
    ax.set_title(f"Positives per year ({cfg['kcore']}-core)")
    peak = yearly.idxmax()
    ax.annotate(f"peak {peak}: {yearly[peak] / 1e3:.0f}k", (peak, yearly[peak]), textcoords="offset points",
                xytext=(8, -4), fontsize=7, color=TEXT_SECONDARY)
    save(fig, os.path.join(fig_dir, "data_positives_per_year.png"))

    print(open(os.path.join(tab_dir, "dataset_stats.md")).read())
    print("figures:", sorted(f for f in os.listdir(fig_dir) if f.startswith("data_")))


if __name__ == "__main__":
    main()
