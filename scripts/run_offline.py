"""
Offline evaluation pipeline (step 4). Every number in the report's offline section comes from here.

    python scripts/run_offline.py --stage all        # tune -> select -> final -> eval
    python scripts/run_offline.py --stage eval       # only recompute tables/figures from existing checkpoints

Stages
  tune    equal-budget grid for BPR-MF and adaptation A      (configs/grids/step4_tune.yaml)
  select  best val NDCG@10 per family, subject to val coverage@10 >= 1% (rules out models that
          collapse into "everyone gets the same popular recipes"); writes configs/grids/step4_final.yaml
          (or <$HEALTHREC_OUTPUTS>/step4_final.yaml when the outputs are redirected)
  final   selected configs x 3 seeds, plus the A+B lambda sweep (ablation)
  eval    test-set tables (outputs/tables/offline_*.csv + offline_results.md) and figures (outputs/figures/offline_*.png)
  blend   popularity calibration: score = z(model) + α·z(log popularity), α chosen on val (coverage@10 >= 1%),
          reported on test as an extra comparison (outputs/tables/offline_blend_*.csv, appended to offline_results.md)
"""
